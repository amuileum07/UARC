"""Generate TypeScript DTOs from the authoritative Pydantic JSON schemas."""

import json
from pathlib import Path

from app.schemas import (
    DesignPreview,
    DesignReport,
    EnvironmentConfig,
    FlightSummary,
    ImportedFile,
    LocationResult,
    OpenRocketImport,
    OpenRocketOptions,
    RocketDesign,
    RunRecord,
    SavedDesignRecord,
    TelemetryResult,
    TerrainGrid,
    TerrainImportOptions,
    TerrainRequest,
    WeatherImportOptions,
    WeatherProfile,
    WeatherRequest,
    WeatherTable,
)


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return "(" + " | ".join(typescript(s) for s in schema[union]) + ")"
    kind = schema.get("type")
    if kind == "object":
        if "properties" not in schema:
            return (
                "Record<string, "
                + typescript(schema.get("additionalProperties", {}))
                + ">"
            )
        required = schema.get("required", [])
        fields = [
            json.dumps(name)
            + ("" if name in required else "?")
            + ": "
            + typescript(value)
            for name, value in schema["properties"].items()
        ]
        return "{\n" + ";\n".join(fields) + "\n}"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(typescript(s) for s in schema["prefixItems"]) + "]"
        return "Array<" + typescript(schema.get("items", {})) + ">"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    definitions = {}
    for model in (
        RocketDesign,
        EnvironmentConfig,
        TerrainGrid,
        TerrainRequest,
        TerrainImportOptions,
        LocationResult,
        WeatherRequest,
        WeatherProfile,
        WeatherImportOptions,
        WeatherTable,
        ImportedFile,
        OpenRocketImport,
        OpenRocketOptions,
        DesignPreview,
        DesignReport,
        RunRecord,
        SavedDesignRecord,
        FlightSummary,
        TelemetryResult,
    ):
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    output = "// Generated by backend/scripts/export_frontend_types.py. Do not edit.\n"
    output += "\n\n".join(
        f"export type {name} = {typescript(schema)};"
        for name, schema in sorted(definitions.items())
    )
    destination = Path(__file__).resolve().parents[2] / "frontend/src/lib/types.ts"
    destination.write_text(output + "\n")


if __name__ == "__main__":
    main()
